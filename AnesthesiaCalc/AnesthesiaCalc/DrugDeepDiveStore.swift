    /// Look up deep-dive data for a given drug by flexible name matching.
    ///
    /// Matching is bidirectional: the store key must be contained in the drug name,
    /// or the drug name must be contained in the store key. This handles both
    /// "丙泊酚" ← "丙泊酚 (Propofol) / 凯酚" and "环泊酚" ← "环泊酚 (Ciprofol)".
    static func data(for drug: AnesthesiaDrug) -> DrugDeepDiveData? {
        let name = drug.name
        // 1. Exact match preferred
        if let exact = all.first(where: { $0.drugName == name }) {
            return exact
        }
        // 2. Longest substring match as fallback (handles aliases like 顺式阿曲库铵 → 阿曲库铵)
        return all
            .filter { name.contains($0.drugName) || $0.drugName.contains(name) }
            .max { $0.drugName.count < $1.drugName.count }
    }
